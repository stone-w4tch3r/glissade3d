    private static readonly Dictionary<string, Dictionary<string, string>> Tables =
        new Dictionary<string, Dictionary<string, string>>
        {
            ["en"] = En,
            ["ru"] = Ru,
            ["de"] = De,
            ["fr"] = Fr,
            ["es"] = Es,
            ["it"] = It,
            ["pt"] = Pt,
            ["ja"] = Ja,
            ["zh"] = Zh
        };

    public static void Initialize()
    {
        _lang = Normalize(Localizer.CurrentLanguage ?? "en");
    }

    public static string Get(string key)
    {
        if (Tables.TryGetValue(_lang, out var table) && table.TryGetValue(key, out var value)) return value;
        return En.TryGetValue(key, out var fallback) ? fallback : key;
    }

    private static string Normalize(string language)
    {
        var lower = language.ToLowerInvariant();
        if (lower.StartsWith("pt")) return "pt";
        if (lower.StartsWith("zh")) return "zh";
        if (lower.StartsWith("es")) return "es";
        if (lower.Length < 2) return "en";
        var two = lower.Substring(0, 2);
        return Tables.ContainsKey(two) ? two : "en";
    }
